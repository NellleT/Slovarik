const DICTS: Record<Lang, Dict> = { ru, en, de };

/** Language names are always shown in their own language. */
export const LANG_NAMES: Record<Lang, string> = { ru: 'Русский', en: 'English', de: 'Deutsch' };

function detect(): Lang {
  const list = typeof navigator !== 'undefined' ? [...(navigator.languages ?? []), navigator.language] : [];
  for (const l of list) {
    const code = l?.slice(0, 2).toLowerCase();
    if (code === 'ru' || code === 'en' || code === 'de') return code;
  }
  return 'en';
}

let current: Lang = detect();

export function setLanguage(pref: LangPref) {
  current = pref === 'auto' ? detect() : pref;
  if (typeof document !== 'undefined') document.documentElement.lang = current;
}

export const lang = () => current;
export const t = (): Dict => DICTS[current];
